/**
 * Syncs curated venues to Cloud Firestore in collection 'curated_venues'
 */
export async function syncCuratedVenuesToFirebase(): Promise<number> {
  if (!isFirebaseConfigured || !db) {
    return PRELOADED_CURATED_VENUES.length;
  }

  try {
    const colRef = collection(db, 'curated_venues');
    for (const venue of PRELOADED_CURATED_VENUES) {
      await setDoc(doc(colRef, venue.id), venue, { merge: true });
    }
    return PRELOADED_CURATED_VENUES.length;
  } catch (err) {
    console.warn('Failed to sync curated venues to Firestore:', err);
    return PRELOADED_CURATED_VENUES.length;
  }
}

/**
 * Fetches curated venues from Firestore if available, otherwise returns preloaded list
 */
export async function getCuratedVenues(stateFilter?: string): Promise<VenueOption[]> {
  if (isFirebaseConfigured && db) {
    try {
      const colRef = collection(db, 'curated_venues');
      const snap = await getDocs(colRef);
      if (!snap.empty) {
        const firestoreVenues: VenueOption[] = [];
        snap.forEach((d) => {
          firestoreVenues.push(d.data() as VenueOption);
        });
        if (stateFilter && stateFilter !== 'ALL') {
          return firestoreVenues.filter((v) => v.curatedState === stateFilter || v.state === stateFilter);
        }
        return firestoreVenues;
      }
    } catch (e) {
      console.warn('Using static preloaded venues fallback:', e);
    }
  }

  // Fallback to static list
  if (stateFilter && stateFilter !== 'ALL') {
    return PRELOADED_CURATED_VENUES.filter(
      (v) => v.curatedState === stateFilter || v.state === stateFilter
    );
  }
  return PRELOADED_CURATED_VENUES;
}
